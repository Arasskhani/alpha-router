function pickMergedTitle(local: ChatSession, remote: ChatSession): string {
  if (local.titleLocked) return local.title;
  if (remote.titleLocked) return remote.title;
  const lt = (local.title || "").trim();
  const rt = (remote.title || "").trim();
  if (isDefaultChatTitle(lt) && !isDefaultChatTitle(rt)) return rt;
  if (!isDefaultChatTitle(lt) && isDefaultChatTitle(rt)) return lt;
  // Prefer substantive titles over truncated/LLM stubs like "قص" vs a full prompt snippet.
  if (!isDefaultChatTitle(lt) && rt.length > 0 && rt.length < 4 && lt.length > rt.length) return lt;
  if (!isDefaultChatTitle(rt) && lt.length > 0 && lt.length < 4 && rt.length > lt.length) return rt;
  if (!isDefaultChatTitle(lt) && !isDefaultChatTitle(rt)) {
    return lt.length >= rt.length ? lt : rt;
  }
  return lt.length >= rt.length ? lt : rt;
}

/**
 * Merge a message-load result into the live sidebar row without wiping a better
 * local title. Lazy loads often still carry the DB default "New chat"; the UI
 * may already have a derived/generated title that has not reached the server yet.
 */
export function mergeSessionAfterMessageLoad(
  local: ChatSession | undefined,
  loaded: ChatSession,
): ChatSession {
  if (!local) return loaded;
  return {
    ...loaded,
    title: pickMergedTitle(local, loaded),
    titleLocked: !!(local.titleLocked || loaded.titleLocked),
    titleGenerated: !!(local.titleGenerated || loaded.titleGenerated),
  };
}

/**
 * Choose which message list survives a merge.
 *
 * A side that has no messages loaded (the list endpoint returns sessions
 * without messages) never wins. When both sides carry messages the newer
 * `updatedAt` wins — so a deletion made on another device does replace the
 * longer, stale list here. Only a timestamp tie falls back to "more messages".
 */
export function pickMergedMessages(
  local: ChatSession,
  remote: ChatSession,
  localUpdated: number = sessionVersionAt(local),
  remoteUpdated: number = sessionVersionAt(remote),
): ChatMessage[] {
  const lm = local.messages.length;
  const rm = remote.messages.length;
  if (rm === 0) return local.messages;
  if (lm === 0) return remote.messages;
  if (remoteUpdated > localUpdated) return remote.messages;
  if (localUpdated > remoteUpdated) return local.messages;
  return lm >= rm ? local.messages : remote.messages;
}

/**
 * Merge remote sessions with local state. Protected ids (streaming / image jobs) always keep local messages.
 * Otherwise the copy with the newer updatedAt wins for every field (title and
 * messages have their own rules above; Agent selection is server-owned).
 */
export function mergeRemoteChatSessions(
  local: ChatSession[],
  remote: ChatSession[],
  protectedIds: Iterable<string> = [],
): ChatSession[] {
  if (!remote.length && local.length) {
    return normalizeChatSessions(local);
  }
  const protect = new Set(protectedIds);
  const remoteById = new Map(remote.map((s) => [s.id, s]));
  const localById = new Map(local.map((s) => [s.id, s]));
  const orderedIds: string[] = [];
  const seen = new Set<string>();
  for (const s of local) {
    if (!seen.has(s.id)) {
      orderedIds.push(s.id);
      seen.add(s.id);
    }
  }
  for (const s of remote) {
    if (!seen.has(s.id)) {
      orderedIds.push(s.id);
      seen.add(s.id);
    }
  }

  const merged: ChatSession[] = [];
  for (const id of orderedIds) {
    if (isPendingDelete(id)) continue;
    const l = localById.get(id);
    const r = remoteById.get(id);
    if (l && !r) {
      merged.push(l);
      continue;
    }
    if (r && !l) {
      merged.push(r);
      continue;
    }
    if (!l || !r) continue;

    const localUpdated = sessionVersionAt(l);
    const remoteUpdated = sessionVersionAt(r);

    const title = pickMergedTitle(l, r);

    if (protect.has(id)) {
      merged.push({
        ...r,
        ...l,
        title: pickMergedTitle(l, r),
        messages: l.messages,
        currentAgentId: r.currentAgentId,
        currentAgentVersionId: r.currentAgentVersionId,
        agentSelectedAt: r.agentSelectedAt,
        updatedAt: Math.max(l.updatedAt ?? 0, r.updatedAt ?? 0),
        lastMessageAt: Math.max(
          l.lastMessageAt ?? sessionActivityAt(l),
          r.lastMessageAt ?? sessionActivityAt(r),
        ),
      });
      continue;
    }

    // Newer copy wins; a tie, or a local change still waiting to be pushed,
    // keeps the local fields.
    const remoteWins = remoteUpdated > localUpdated && !hasUnsyncedLocalWrites(id);
    const messages = remoteWins
      ? pickMergedMessages(l, r, localUpdated, remoteUpdated)
      : pickMergedMessages(l, r, 1, 0);
    const base = remoteWins ? { ...l, ...r } : { ...r, ...l };
    merged.push({
      ...base,
      title,
      messages,
      currentAgentId: r.currentAgentId,
      currentAgentVersionId: r.currentAgentVersionId,
      agentSelectedAt: r.agentSelectedAt,
      updatedAt: Math.max(l.updatedAt ?? 0, r.updatedAt ?? 0),
    });
  }

  return normalizeChatSessions(merged);
}

