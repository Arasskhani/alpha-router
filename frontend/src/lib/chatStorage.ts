function normalizeUserPrefs(raw?: Partial<UserPrefs> | null): UserPrefs {
  const model = typeof raw?.default_model === "string" && raw.default_model.trim()
    ? raw.default_model.trim()
    : null;
  const themeRaw = typeof raw?.theme === "string" ? raw.theme.trim().toLowerCase() : "light";
  const theme: UserTheme = isCachedTheme(themeRaw) ? themeRaw : "light";
  const timezone = typeof raw?.timezone === "string" && raw.timezone.trim()
    ? raw.timezone.trim()
    : "UTC";
  const voiceRecordingLang = normalizeVoiceLang(
    typeof raw?.voice_recording_language === "string" ? raw.voice_recording_language : null,
  );
  const transcriptionModel =
    typeof raw?.transcription_model === "string" ? raw.transcription_model.trim() : "";
  const persianRaw = typeof raw?.persian_font === "string" ? raw.persian_font.trim() : "";
  const persianFont =
    !persianRaw || persianRaw.toLowerCase() === "system" || persianRaw.toLowerCase() === "default"
      ? ""
      : persianRaw.slice(0, 64);
  const replyNotifyAway = coercePrefsBool(raw?.reply_notify_away, false);
  const replyNotifySound = coercePrefsBool(raw?.reply_notify_sound, true);
  const memoryEnabled = coercePrefsBool(raw?.memory_enabled, true);
  const memoryAutoCapture = coercePrefsBool(raw?.memory_auto_capture, true);
  const memoryOutsideChat = coercePrefsBool(raw?.memory_outside_chat, false);
  return {
    default_model: model,
    theme,
    timezone,
    voice_recording_language: voiceRecordingLang,
    transcription_model: transcriptionModel,
    persian_font: persianFont,
    reply_notify_away: replyNotifyAway,
    reply_notify_sound: replyNotifySound,
    memory_enabled: memoryEnabled,
    memory_auto_capture: memoryAutoCapture,
    memory_outside_chat: memoryOutsideChat,
  };
}

function coercePrefsBool(value: unknown, defaultValue: boolean): boolean {
  if (typeof value === "boolean") return value;
  if (value === 0 || value === 1) return Boolean(value);
  if (typeof value === "string") {
    const token = value.trim().toLowerCase();
    if (token === "1" || token === "true" || token === "yes" || token === "on") return true;
    if (token === "0" || token === "false" || token === "no" || token === "off" || token === "") return false;
  }
  return defaultValue;
}

