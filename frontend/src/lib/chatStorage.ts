export async function loadPrivateChatSessions(): Promise<ChatSession[]> {
  try {
    const raw = localStorage.getItem(privateChatStorageKey());
    if (!raw) return [];
    const parsed = normalizeChatSessions(JSON.parse(raw) as ChatSession[]);
    if (privateSessionsNeedStorageMigration(parsed)) {
      const compacted = await compactPrivateSessionsForStorage(parsed);
      try {
        localStorage.setItem(privateChatStorageKey(), JSON.stringify(compacted));
      } catch (err) {
        if (isQuotaExceededError(err)) {
          throw new PrivateChatStorageError(
            "Could not migrate private chat media: browser storage is full. Delete old private chats or clear site data.",
          );
        }
        throw err;
      }
      return hydratePrivateSessionsFromStorage(compacted);
    }
    return hydratePrivateSessionsFromStorage(parsed);
  } catch (err) {
    if (err instanceof PrivateChatStorageError) throw err;
    return [];
  }
}

