function messageActivityMs(m: ChatMessage): number {
  return Math.max(m.sentAt ?? 0, m.receivedAt ?? 0);
}

/** Last user-visible activity for sidebar ordering (not metadata edits). */
export function sessionActivityAt(s: ChatSession): number {
  if (s.lastMessageAt) return s.lastMessageAt;
  if (s.messages.length) {
    let max = 0;
    for (const m of s.messages) {
      max = Math.max(max, messageActivityMs(m));
    }
    if (max > 0) return max;
  }
  return s.createdAt;
}

/** Newest known change to a session — metadata edits included (unlike sessionActivityAt). */
function sessionVersionAt(s: ChatSession): number {
  return Math.max(s.updatedAt ?? 0, sessionActivityAt(s));
}

export function sortSessionsByActivity(sessions: ChatSession[]): ChatSession[] {
  return [...sessions].sort((a, b) => sessionActivityAt(b) - sessionActivityAt(a));
}

export function withSessionMessagesActivity(
  session: ChatSession,
  messages: ChatMessage[],
): ChatSession {
  let last = 0;
  for (const m of messages) {
    last = Math.max(last, messageActivityMs(m));
  }
  const lastMessageAt = last > 0 ? last : session.lastMessageAt ?? session.createdAt;
  return { ...session, messages, lastMessageAt };
}

